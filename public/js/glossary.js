// Up to `max` terms found in the text, in the order they first appear.
export function termsFor(text, max = 4) {
  const s = String(text || '');
  return TERMS.map(([trLabel, enLabel, re, tr, en]) => {
    const m = s.match(re);
    return m ? { at: m.index, label: lang === 'tr' ? trLabel : enLabel, text: lang === 'tr' ? tr : en } : null;
  }).filter(Boolean).sort((a, b) => a.at - b.at).slice(0, max);
}
